#!/usr/bin/env python3
"""Packs the readable model tables (tools/tables/) into the C data the
program is built from:

  tools/tables/ExeModelTables.c -> src/model/ExeModelTables.inc
  tools/tables/StateTables.c    -> src/StateTableData.inc

Run it from the project root after changing a table:  python3 tools/pack_tables.py

The packed forms (expanded at startup, see src/Rle.h, StateTable_init() and
ExeModel_new()):

  run-length codes  one byte per run: the value in the low valueBits bits,
                    (run length - 1) in the high bits
  state tables      states 0..148 are stored; 149..255 follow a formula, which
                    is checked here against the readable table
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8-sig") as f:
        return f.read()


def write(path, text):
    with open(os.path.join(ROOT, path), "w", encoding="utf-8-sig", newline="\r\n") as f:
        f.write(text)


def strip_comments(text):
    return re.sub(r"//[^\n]*", "", text)


def parse_array(text, name, env=None):
    m = re.search(r"static const uint8_t " + name + r"\s*((?:\[\d+\])+)\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit("table not found: " + name)
    size = 1
    for d in re.findall(r"\[(\d+)\]", m.group(1)):
        size *= int(d)
    body = strip_comments(m.group(2)).replace("{", " ").replace("}", " ")
    values = [eval(e, {}, env or {}) for e in (x.strip() for x in body.split(",")) if e]
    if len(values) != size:
        sys.exit("%s: %d values instead of %d" % (name, len(values), size))
    return values


def rle(values, value_bits):
    """One byte per run: value | (length - 1) << value_bits."""
    max_run = 1 << (8 - value_bits)
    out = []
    i = 0
    while i < len(values):
        v = values[i]
        if v >= 1 << value_bits:
            sys.exit("value %d does not fit in %d bits" % (v, value_bits))
        j = i
        while j < len(values) and values[j] == v and j - i < max_run:
            j += 1
        out.append(v | (j - i - 1) << value_bits)
        i = j
    return out


def unrle(codes, value_bits, n):
    out = []
    for c in codes:
        out += [c & ((1 << value_bits) - 1)] * ((c >> value_bits) + 1)
    assert len(out) == n
    return out


def c_bytes(name, values, comment):
    lines = ["// " + comment, "static const uint8_t %s[%d] = {" % (name, len(values))]
    for i in range(0, len(values), 16):
        lines.append("  " + ", ".join("%d" % v for v in values[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


HEADER = "// Generated by tools/pack_tables.py from %s - do not edit.\n\n"


def pack_exe_tables():
    code = read("src/model/ExeModel.c")
    env = {}
    for m in re.finditer(r"\b(f[A-Z]+|OP_[A-Z0-9_]+)\s*=\s*(0x[0-9a-fA-F]+|\d+)", code):
        env[m.group(1)] = int(m.group(2), 0)
    text = read("tools/tables/ExeModelTables.c")
    flags = []
    categories = []
    for t, c in (("table1", "typeOp1"), ("table2", "typeOp2"), ("table3_38", "typeOp3_38"),
                 ("table3_3A", "typeOp3_3A"), ("tableX", "typeOpX")):
        flags += parse_array(text, t, env)
        categories += parse_array(text, c, env)
    f = rle(flags, 4)
    c = rle(categories, 5)
    assert unrle(f, 4, len(flags)) == flags and unrle(c, 5, len(categories)) == categories
    out = HEADER % "tools/tables/ExeModelTables.c"
    out += "#define EXE_TABLES_SIZE %d // table1, table2, table3_38, table3_3A (256 each), tableX (32)\n\n" % len(flags)
    out += c_bytes("exeFlagsRle", f, "the opcode formats (fMR, ...): run-length codes, 4-bit values")
    out += "\n" + c_bytes("exeCategoriesRle", c, "the opcode categories (OP_...): run-length codes, 5-bit values")
    write("src/model/ExeModelTables.inc", out)
    return len(flags) * 2, len(f) + len(c)


HEAD = 149  # states 149.. follow a formula


def state_formula(i):
    """The row of stateTable, the group and the priority of state i >= HEAD."""
    if i >= 253:  # unused
        return [1, 2, 0, 0], 0, 0
    k, j = divmod(i - HEAD, 4)
    advance = min(i + 4, 249 + j)
    other = (95, 69, 80, 100)[j]
    row = ([advance, other, 16 + k, 0], [advance, other, 15 + k, 1],
           [other, advance, 1, 15 + k], [other, advance, 0, 16 + k])[j]
    group = ((19 if k < 15 else 20), (22 if k < 5 else 21), (30 if k < 5 else 31), (16 if k < 14 else 17))[j]
    prio = (31 + 2 * k, 28 + 2 * k, 28 + 2 * k, 31 + 2 * k)[j]
    return row, group, prio


def pack_state_tables():
    text = read("tools/tables/StateTables.c")
    table = parse_array(text, "stateTable")
    rows = [table[i * 4:i * 4 + 4] for i in range(256)]
    group = parse_array(text, "stateGroup")
    prio = parse_array(text, "statePrio")
    for i in range(HEAD, 256):
        if state_formula(i) != (rows[i], group[i], prio[i]):
            sys.exit("state %d does not follow the formula of StateTable_init()" % i)
    nexts = [v for r in rows[:HEAD] for v in r[:2]]
    counts = []
    for r in rows[:HEAD]:
        if r[2] > 15 or r[3] > 15:
            sys.exit("counts do not fit in 4 bits")
        counts.append(r[2] | r[3] << 4)
    g = rle(group[:HEAD], 5)
    p = rle(prio[:HEAD], 5)
    assert unrle(g, 5, HEAD) == group[:HEAD] and unrle(p, 5, HEAD) == prio[:HEAD]
    out = HEADER % "tools/tables/StateTables.c"
    out += "#define STATE_TABLE_HEAD %d // the stored states; the rest follow a formula\n\n" % HEAD
    out += c_bytes("stateNextHead", nexts, "the next state after a 0 and a 1 bit, 2 bytes per state")
    out += "\n" + c_bytes("stateCountsHead", counts, "the bit counts: n0 | n1 << 4")
    out += "\n" + c_bytes("stateGroupRle", g, "the state groups: run-length codes, 5-bit values")
    out += "\n" + c_bytes("statePrioRle", p, "the state priorities: run-length codes, 5-bit values")
    write("src/StateTableData.inc", out)
    return 256 * 6, len(nexts) + len(counts) + len(g) + len(p)


if __name__ == "__main__":
    for name, (before, after) in (("ExeModel tables", pack_exe_tables()), ("state tables", pack_state_tables())):
        print("%s: %d -> %d bytes" % (name, before, after))
